let language: Language = "tr";

export function setLanguage(lang: Language): void {
  language = lang;
  document.documentElement.lang = lang;
}

export function getLanguage(): Language {
  return language;
}

export type TextKey = Key;

/** Translates `key`, filling `{param}` placeholders. */
export function t(key: Key, params?: Record<string, string | number>): string {
  let s = (language === "tr" ? tr[key] : en[key]) ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function objectName(id: string): string {
  return language === "tr" ? (objectNamesTr[id]?.[0] ?? OBJECTS[id]?.name ?? id) : (OBJECTS[id]?.name ?? id);
}

export function objectDescription(id: string): string {
  return language === "tr" ? (objectNamesTr[id]?.[1] ?? OBJECTS[id]?.description ?? "") : (OBJECTS[id]?.description ?? "");
}

export function toolName(id: string): string {
  return language === "tr" ? (toolNamesTr[id]?.[0] ?? TOOLS[id]?.name ?? id) : (TOOLS[id]?.name ?? id);
}

export function toolTagline(id: string): string {
  return language === "tr" ? (toolNamesTr[id]?.[1] ?? TOOLS[id]?.tagline ?? "") : (TOOLS[id]?.tagline ?? "");
}

export function toolDescription(id: string): string {
  return language === "tr" ? (toolNamesTr[id]?.[2] ?? TOOLS[id]?.description ?? "") : (TOOLS[id]?.description ?? "");
}

/** Every catalog entry has a Turkish name (checked by the tests). */
export function missingTranslations(): string[] {
  const missing: string[] = [];
  for (const id of Object.keys(OBJECTS)) if (!objectNamesTr[id]) missing.push(`object ${id}`);
  for (const id of Object.keys(TOOLS)) if (!toolNamesTr[id]) missing.push(`tool ${id}`);
  return missing;
}

/** Credits as "1.240 CR" (Turkish grouping) or "1,240 CR". */
export function formatCredits(value: number): string {
  return `${Math.round(value).toLocaleString(language === "tr" ? "tr-TR" : "en-US")} CR`;
}

export function formatDuration(seconds: number): string {
  const m = Math.floor(seconds / 60);
  const h = Math.floor(m / 60);
  const [hu, mu] = language === "tr" ? ["sa", "dk"] : ["h", "min"];
  return h > 0 ? `${h} ${hu} ${m % 60} ${mu}` : `${m} ${mu}`;
}

export function formatDate(ms: number): string {
  try {
    return new Date(ms).toLocaleString(language === "tr" ? "tr-TR" : "en-GB", { dateStyle: "short", timeStyle: "short" });
  } catch {
    return new Date(ms).toISOString();
  }
}
